import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { PROVIDERS, PROVIDER_ALIASES } from '../constants.js';
import { parseConfigFile, assertObjectConfig } from '../config.js';
import { issue } from '../errors.js';

const FREE_PLAN_NAMES = Object.freeze({
  render: new Set(['free']),
  railway: new Set(['free', 'trial']),
  vercel: new Set(['free', 'hobby']),
  cloudflare: new Set(['free', 'workers free']),
  gas: new Set(['free', 'consumer']),
});

const RENDER_TYPES = new Set(['static', 'web', 'worker', 'cron', 'pserv']);
const RAILWAY_BUILDERS = new Set(['DOCKERFILE', 'RAILPACK']);

export function normalizeProvider(value) {
  if (value === 'all' || value === 'auto' || value === 'generic') return value;
  const normalized = String(value ?? '').trim().toLowerCase();
  const canonical = PROVIDER_ALIASES[normalized] ?? normalized;
  if (canonical in PROVIDERS) return canonical;
  return undefined;
}

export function detectProviders(files) {
  const basenames = new Set(files.map((file) => path.posix.basename(file.path)));
  const found = [];
  for (const [id, provider] of Object.entries(PROVIDERS)) {
    if (provider.configNames.some((name) => basenames.has(name))) found.push(id);
  }
  return found;
}

function isFreePlan(provider, plan) {
  return FREE_PLAN_NAMES[provider]?.has(String(plan ?? '').toLowerCase()) ?? false;
}

function isCalendarDate(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const parsed = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(parsed.getTime()) && parsed.toISOString().slice(0, 10) === value;
}

function addTypeIssue(issues, value, file, field, expected) {
  if (value !== undefined && typeof value !== expected) {
    issues.push(issue('error', 'CONFIG_FIELD_TYPE', `${field} must be ${expected}.`, file));
    return false;
  }
  return true;
}

function validateString(value, file, field, issues, { required = false, nonEmpty = true } = {}) {
  if (value === undefined || value === null) {
    if (required) issues.push(issue('error', 'CONFIG_FIELD_REQUIRED', `${field} is required.`, file));
    return false;
  }
  if (typeof value !== 'string' || (nonEmpty && value.trim() === '')) {
    issues.push(issue('error', 'CONFIG_FIELD_TYPE', `${field} must be a non-empty string.`, file));
    return false;
  }
  return true;
}

function configFiles(files, provider) {
  const names = new Set(PROVIDERS[provider].configNames);
  return files
    .filter((item) => names.has(path.posix.basename(item.path)))
    .map((item) => ({ ...item, dir: parentDir(item.path) }));
}

function parentDir(file) {
  const directory = path.posix.dirname(file);
  return directory === '.' ? '.' : directory;
}

function joinProjectPath(baseDir, child) {
  return path.posix.normalize(path.posix.join(baseDir === '.' ? '' : baseDir, child));
}

function isContainedPath(root, candidate) {
  const relative = path.relative(path.resolve(root), path.resolve(candidate));
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative));
}

async function validatePathExists(projectRoot, baseDir, value, file, issues, {
  field,
  expectDirectory = undefined,
  missingSeverity = 'warning',
  allowMissing = false,
} = {}) {
  if (typeof value !== 'string' || value.trim() === '') return null;
  const base = path.resolve(projectRoot, baseDir === '.' ? '' : baseDir);
  const absolute = path.resolve(base, value);
  if (!isContainedPath(projectRoot, absolute)) {
    issues.push(issue('error', 'CONFIG_PATH_ESCAPES_PROJECT', `${field} points outside the project directory.`, file,
      'Use a relative path contained within the checked project.'));
    return null;
  }
  try {
    const info = await stat(absolute);
    if (expectDirectory === true && !info.isDirectory()) {
      issues.push(issue('error', 'CONFIG_PATH_NOT_DIRECTORY', `${field} points to a file, not a directory.`, file));
      return absolute;
    }
    if (expectDirectory === false && !info.isFile()) {
      issues.push(issue('error', 'CONFIG_PATH_NOT_FILE', `${field} points to a directory, not a file.`, file));
      return absolute;
    }
    return absolute;
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      issues.push(issue('error', 'CONFIG_PATH_CHECK_FAILED', `Cannot inspect ${field}: ${error.message}`, file));
      return null;
    }
    if (!allowMissing) {
      const message = missingSeverity === 'info'
        ? `${field} is not present before build (it may be generated): ${value}`
        : `${field} does not exist: ${value}`;
      issues.push(issue(missingSeverity, 'CONFIG_PATH_NOT_FOUND', message, file,
        missingSeverity === 'warning' ? 'It may be generated by the build; run dotdeployer test with --build to verify it.' : undefined));
    }
    return null;
  }
}

async function validateRender(projectRoot, files, plan, issues) {
  const configs = configFiles(files, 'render');
  if (!configs.length) {
    issues.push(issue('warning', 'PROVIDER_CONFIG_MISSING', 'No render.yaml or render.yml Blueprint was found. Render can deploy without a Blueprint, but provider-specific checks are limited.'));
    return;
  }
  if (configs.length > 1) {
    issues.push(issue('warning', 'MULTIPLE_PROVIDER_CONFIGS', `Found ${configs.length} Render Blueprint files; each is checked independently.`));
  }
  for (const item of configs) {
    const data = await parseConfigFile(projectRoot, item.path, issues);
    if (data === undefined || !assertObjectConfig(data, item.path, issues, 'Render Blueprint')) continue;
    if (!Array.isArray(data.services) || data.services.length === 0) {
      issues.push(issue('error', 'RENDER_SERVICES_REQUIRED', 'Render Blueprint must define a non-empty services array.', item.path));
      continue;
    }
    const groups = new Set((Array.isArray(data.envVarGroups) ? data.envVarGroups : [])
      .map((group) => group?.name).filter((name) => typeof name === 'string'));

    for (const [index, service] of data.services.entries()) {
      if (!service || typeof service !== 'object' || Array.isArray(service)) {
        issues.push(issue('error', 'RENDER_SERVICE_INVALID', `Service at index ${index} must be an object.`, item.path));
        continue;
      }
      validateString(service.name, item.path, `services[${index}].name`, issues, { required: true });
      if (!RENDER_TYPES.has(service.type)) {
        issues.push(issue('error', 'RENDER_SERVICE_TYPE_INVALID', `Unsupported Render service type ${JSON.stringify(service.type)}. Expected one of: ${[...RENDER_TYPES].join(', ')}.`, item.path));
      }
      let serviceRoot = item.dir;
      if (service.rootDir !== undefined) {
        if (typeof service.rootDir !== 'string' || service.rootDir.trim() === '') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', `services[${index}].rootDir must be a non-empty relative path.`, item.path));
        } else if (path.posix.isAbsolute(service.rootDir)) {
          issues.push(issue('error', 'CONFIG_PATH_ESCAPES_PROJECT', `services[${index}].rootDir must be relative to the project.`, item.path));
        } else {
          serviceRoot = joinProjectPath(item.dir, service.rootDir);
          await validatePathExists(projectRoot, '.', serviceRoot, item.path, issues, {
            field: `services[${index}].rootDir`, expectDirectory: true, missingSeverity: 'error',
          });
        }
      }
      if (service.buildCommand !== undefined) addTypeIssue(issues, service.buildCommand, item.path, `services[${index}].buildCommand`, 'string');
      if (service.startCommand !== undefined) addTypeIssue(issues, service.startCommand, item.path, `services[${index}].startCommand`, 'string');
      for (const field of ['dockerfilePath', 'dockerContext']) {
        if (service[field] !== undefined && typeof service[field] !== 'string') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', `services[${index}].${field} must be a string.`, item.path));
        }
      }
      if (service.dockerfilePath || String(service.runtime ?? '').toLowerCase() === 'docker') {
        const dockerfilePath = typeof service.dockerfilePath === 'string' ? service.dockerfilePath : 'Dockerfile';
        await validatePathExists(projectRoot, serviceRoot, dockerfilePath, item.path, issues, {
          field: `services[${index}].dockerfilePath`, expectDirectory: false, missingSeverity: 'error',
        });
        const deployPath = path.posix.normalize(path.posix.join(serviceRoot === '.' ? '' : serviceRoot, dockerfilePath));
        if (!files.some((file) => file.path === deployPath)) {
          issues.push(issue('error', 'DOCKERFILE_NOT_IN_DEPLOY_CONTEXT', `Render Dockerfile is not included in the deployable Git context: ${deployPath}.`, item.path));
        }
      }
      if (service.dockerContext) {
        await validatePathExists(projectRoot, serviceRoot, service.dockerContext, item.path, issues, {
          field: `services[${index}].dockerContext`, expectDirectory: true, missingSeverity: 'error',
        });
      }
      if (service.type === 'static') {
        if (!validateString(service.staticPublishPath, item.path, `services[${index}].staticPublishPath`, issues, { required: true })) {
          // The publish directory may be created during the provider build.
        } else if (path.posix.isAbsolute(service.staticPublishPath)) {
          issues.push(issue('error', 'CONFIG_PATH_ESCAPES_PROJECT', `services[${index}].staticPublishPath must be relative to the service root.`, item.path));
        } else {
          const publishPath = joinProjectPath(serviceRoot, service.staticPublishPath);
          await validatePathExists(projectRoot, '.', publishPath, item.path, issues, {
            field: `services[${index}].staticPublishPath`, expectDirectory: true, missingSeverity: 'info',
          });
        }
      } else if (service.type && RENDER_TYPES.has(service.type) && !service.startCommand && !service.dockerCommand) {
        issues.push(issue('warning', 'RENDER_START_COMMAND_UNVERIFIED', `services[${index}] has no explicit startCommand; Render may infer one from the runtime.`, item.path,
          'Set startCommand explicitly when relying on a particular runtime or process entry point.'));
      }
      if (service.envVars !== undefined && !Array.isArray(service.envVars)) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', `services[${index}].envVars must be an array.`, item.path));
      }
      for (const [envIndex, envVar] of (Array.isArray(service.envVars) ? service.envVars : []).entries()) {
        if (!envVar || typeof envVar !== 'object' || Array.isArray(envVar)) {
          issues.push(issue('error', 'RENDER_ENV_VAR_INVALID', `services[${index}].envVars[${envIndex}] must be an object.`, item.path));
          continue;
        }
        if (envVar.key !== undefined) validateString(envVar.key, item.path, `services[${index}].envVars[${envIndex}].key`, issues, { required: true });
        if (envVar.value !== undefined && typeof envVar.value !== 'string' && typeof envVar.value !== 'number' && typeof envVar.value !== 'boolean') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', `services[${index}].envVars[${envIndex}].value must be a scalar.`, item.path));
        }
        if (typeof envVar.value === 'string' && /(?:secret|token|password|private[_-]?key|api[_-]?key)/i.test(envVar.key ?? '')) {
          issues.push(issue('warning', 'POSSIBLE_SECRET_IN_CONFIG', `Environment variable ${envVar.key} may contain a secret in a committed Blueprint.`, item.path,
            'Use the provider secret store or a Render fromGroup reference instead of committing secret values.'));
        }
        if (envVar.fromGroup && !groups.has(envVar.fromGroup)) {
          issues.push(issue('warning', 'ENV_GROUP_NOT_DECLARED', `Environment group ${envVar.fromGroup} is referenced but not declared in this Blueprint.`, item.path));
        }
      }
      if (service.disk && isFreePlan('render', plan)) {
        issues.push(issue('error', 'PLAN_LIMIT_DISK', `services[${index}] configures persistent disk storage, which is not accepted by the local Render Free profile.`, item.path,
          'Remove the disk declaration or select a paid plan that supports persistent disks.'));
      }
      if (service.plan !== undefined && isFreePlan('render', plan) && String(service.plan).toLowerCase() !== 'free') {
        issues.push(issue('error', 'PLAN_MISMATCH', `services[${index}] requests plan ${JSON.stringify(service.plan)} but the selected profile is Free.`, item.path,
          'Change the service plan or run with --plan paid.'));
      }
    }
  }
}

async function validateRailway(projectRoot, files, plan, issues) {
  const configs = configFiles(files, 'railway');
  if (!configs.length) {
    issues.push(issue('warning', 'PROVIDER_CONFIG_MISSING', 'No railway.json or railway.toml was found. Railway can infer deployment settings, but provider-specific checks are limited.'));
    return;
  }
  if (configs.length > 1) issues.push(issue('warning', 'MULTIPLE_PROVIDER_CONFIGS', 'Found multiple Railway config files; each is checked independently.'));
  for (const item of configs) {
    const data = await parseConfigFile(projectRoot, item.path, issues);
    if (data === undefined || !assertObjectConfig(data, item.path, issues, 'Railway')) continue;
    const build = data.build;
    const deploy = data.deploy;
    if (build !== undefined && (!build || typeof build !== 'object' || Array.isArray(build))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'build must be an object.', item.path));
    } else if (build) {
      if (build.builder !== undefined) {
        if (typeof build.builder !== 'string') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'build.builder must be a string.', item.path));
        } else if (!RAILWAY_BUILDERS.has(build.builder.toUpperCase())) {
          issues.push(issue('warning', 'RAILWAY_BUILDER_UNKNOWN', `Unrecognized Railway builder ${JSON.stringify(build.builder)}.`, item.path,
            `Known builder names in this checker: ${[...RAILWAY_BUILDERS].join(', ')}.`));
        }
      }
      for (const field of ['buildCommand', 'watchPatterns', 'dockerfilePath', 'dockerContext']) {
        if (build[field] !== undefined && field !== 'watchPatterns' && typeof build[field] !== 'string') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', `build.${field} must be a string.`, item.path));
        }
      }
      if (build.dockerfilePath) {
        await validatePathExists(projectRoot, item.dir, build.dockerfilePath, item.path, issues, {
          field: 'build.dockerfilePath', expectDirectory: false, missingSeverity: 'error',
        });
      } else if (String(build.builder ?? '').toUpperCase() === 'DOCKERFILE') {
        await validatePathExists(projectRoot, item.dir, 'Dockerfile', item.path, issues, {
          field: 'Dockerfile', expectDirectory: false, missingSeverity: 'error',
        });
      }
      if (build.dockerContext) {
        await validatePathExists(projectRoot, item.dir, build.dockerContext, item.path, issues, {
          field: 'build.dockerContext', expectDirectory: true, missingSeverity: 'error',
        });
      }
      if (String(build.builder ?? '').toUpperCase() === 'DOCKERFILE' || build.dockerfilePath) {
        const configuredPath = typeof build.dockerfilePath === 'string' ? build.dockerfilePath : 'Dockerfile';
        const deployPath = path.posix.normalize(path.posix.join(item.dir === '.' ? '' : item.dir, configuredPath));
        if (!files.some((file) => file.path === deployPath)) {
          issues.push(issue('error', 'DOCKERFILE_NOT_IN_DEPLOY_CONTEXT', `Railway Dockerfile is not included in the deployable Git context: ${deployPath}.`, item.path));
        }
      }
    }
    if (deploy !== undefined && (!deploy || typeof deploy !== 'object' || Array.isArray(deploy))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'deploy must be an object.', item.path));
    } else if (deploy) {
      for (const field of ['startCommand', 'preDeployCommand', 'healthcheckPath', 'cronSchedule']) {
        if (deploy[field] !== undefined && typeof deploy[field] !== 'string') {
          issues.push(issue('error', 'CONFIG_FIELD_TYPE', `deploy.${field} must be a string.`, item.path));
        }
      }
      if (typeof deploy.healthcheckPath === 'string' && deploy.healthcheckPath && !deploy.healthcheckPath.startsWith('/')) {
        issues.push(issue('error', 'RAILWAY_HEALTHCHECK_PATH_INVALID', 'deploy.healthcheckPath must start with /.', item.path));
      }
      if (deploy.healthcheckTimeout !== undefined && (!Number.isInteger(deploy.healthcheckTimeout) || deploy.healthcheckTimeout <= 0)) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'deploy.healthcheckTimeout must be a positive integer.', item.path));
      }
      const policies = new Set(['ON_FAILURE', 'ALWAYS', 'NEVER']);
      if (deploy.restartPolicyType !== undefined && (typeof deploy.restartPolicyType !== 'string' || !policies.has(deploy.restartPolicyType.toUpperCase()))) {
        issues.push(issue('error', 'RAILWAY_RESTART_POLICY_INVALID', 'deploy.restartPolicyType must be ON_FAILURE, ALWAYS, or NEVER.', item.path));
      }
      if (deploy.restartPolicyMaxRetries !== undefined && (!Number.isInteger(deploy.restartPolicyMaxRetries) || deploy.restartPolicyMaxRetries < 0)) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'deploy.restartPolicyMaxRetries must be a non-negative integer.', item.path));
      }
      if (deploy.numReplicas !== undefined && (!Number.isInteger(deploy.numReplicas) || deploy.numReplicas < 1)) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'deploy.numReplicas must be a positive integer.', item.path));
      }
    }
    if (isFreePlan('railway', plan) && Number(deploy?.numReplicas ?? 1) > 1) {
      issues.push(issue('warning', 'PLAN_LIMIT_UNVERIFIED', 'The selected Railway Free profile may not support multiple replicas; verify current plan limits before deploying.', item.path));
    }
    if (!deploy?.startCommand && !files.some((file) => path.posix.basename(file.path) === 'Dockerfile')) {
      issues.push(issue('warning', 'RAILWAY_START_COMMAND_UNVERIFIED', 'No explicit deploy.startCommand or Dockerfile was found; Railway may infer the runtime command.', item.path,
        'Set deploy.startCommand explicitly to make the local build check closer to deployment.'));
    }
  }
}

async function validateVercel(projectRoot, files, plan, issues) {
  const configs = configFiles(files, 'vercel');
  if (!configs.length) {
    issues.push(issue('warning', 'PROVIDER_CONFIG_MISSING', 'No vercel.json was found. Vercel framework auto-detection may still apply; provider-specific checks are limited.'));
    return;
  }
  if (configs.length > 1) issues.push(issue('warning', 'MULTIPLE_PROVIDER_CONFIGS', 'Found multiple vercel.json files; each is checked independently.'));
  for (const item of configs) {
    const data = await parseConfigFile(projectRoot, item.path, issues);
    if (data === undefined || !assertObjectConfig(data, item.path, issues, 'Vercel')) continue;
    for (const field of ['buildCommand', 'installCommand', 'devCommand', 'outputDirectory', 'framework', 'ignoreCommand']) {
      if (data[field] !== undefined && typeof data[field] !== 'string') {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', `${field} must be a string.`, item.path));
      }
    }
    for (const field of ['cleanUrls', 'trailingSlash']) {
      if (data[field] !== undefined && typeof data[field] !== 'boolean') {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', `${field} must be a boolean.`, item.path));
      }
    }
    for (const field of ['rewrites', 'redirects', 'headers', 'routes', 'builds', 'crons']) {
      if (data[field] !== undefined && !Array.isArray(data[field])) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', `${field} must be an array.`, item.path));
      }
    }
    for (const field of ['rewrites', 'redirects']) {
      for (const [index, route] of (Array.isArray(data[field]) ? data[field] : []).entries()) {
        if (!route || typeof route !== 'object' || Array.isArray(route) || typeof route.source !== 'string' || typeof route.destination !== 'string') {
          issues.push(issue('error', 'VERCEL_ROUTE_INVALID', `${field}[${index}] requires string source and destination fields.`, item.path));
        }
      }
    }
    for (const [index, header] of (Array.isArray(data.headers) ? data.headers : []).entries()) {
      if (!header || typeof header !== 'object' || typeof header.source !== 'string' || !Array.isArray(header.headers)) {
        issues.push(issue('error', 'VERCEL_HEADER_RULE_INVALID', `headers[${index}] requires a source string and headers array.`, item.path));
      }
    }
    if (data.outputDirectory) {
      await validatePathExists(projectRoot, item.dir, data.outputDirectory, item.path, issues, {
        field: 'outputDirectory', expectDirectory: true, missingSeverity: 'info',
      });
    }
    if (data.functions !== undefined && (!data.functions || typeof data.functions !== 'object' || Array.isArray(data.functions))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'functions must be an object keyed by function glob.', item.path));
    } else if (data.functions && typeof data.functions === 'object') {
      for (const [pattern, settings] of Object.entries(data.functions)) {
        if (!settings || typeof settings !== 'object' || Array.isArray(settings)) {
          issues.push(issue('error', 'VERCEL_FUNCTION_CONFIG_INVALID', `functions[${JSON.stringify(pattern)}] must be an object.`, item.path));
          continue;
        }
        for (const field of ['maxDuration', 'memory']) {
          if (settings[field] !== undefined && (!Number.isInteger(settings[field]) || settings[field] <= 0)) {
            issues.push(issue('error', 'CONFIG_FIELD_TYPE', `functions[${JSON.stringify(pattern)}].${field} must be a positive integer.`, item.path));
          }
        }
      }
    }
    if (isFreePlan('vercel', plan) && Array.isArray(data.crons) && data.crons.length) {
      issues.push(issue('warning', 'PLAN_LIMIT_UNVERIFIED', 'Cron support and frequency limits vary by Vercel plan and can change; this checker cannot verify them offline.', item.path,
        'Verify the schedule against your current Vercel plan limits.'));
    }
    if (data.env && typeof data.env === 'object' && !Array.isArray(data.env)) {
      for (const key of Object.keys(data.env)) {
        if (/(?:secret|token|password|private[_-]?key|api[_-]?key)/i.test(key)) {
          issues.push(issue('warning', 'POSSIBLE_SECRET_IN_CONFIG', `Vercel env key ${key} looks sensitive; confirm that no secret value is committed.`, item.path));
        }
      }
    }
  }
}

async function validateCloudflare(projectRoot, files, plan, issues) {
  const configs = configFiles(files, 'cloudflare');
  if (!configs.length) {
    issues.push(issue('warning', 'PROVIDER_CONFIG_MISSING', 'No Wrangler config was found. Cloudflare can deploy with command-line defaults, but provider-specific checks are limited.'));
    return;
  }
  if (configs.length > 1) issues.push(issue('warning', 'MULTIPLE_PROVIDER_CONFIGS', 'Found multiple Wrangler config files; each is checked independently.'));
  for (const item of configs) {
    const data = await parseConfigFile(projectRoot, item.path, issues);
    if (data === undefined || !assertObjectConfig(data, item.path, issues, 'Wrangler')) continue;
    if (data.name !== undefined) validateString(data.name, item.path, 'name', issues, { required: true });
    if (data.main !== undefined) {
      if (validateString(data.main, item.path, 'main', issues, { required: true })) {
        await validatePathExists(projectRoot, item.dir, data.main, item.path, issues, {
          field: 'main', expectDirectory: false, missingSeverity: 'error',
        });
      }
    }
    const pagesOutput = data.pages_build_output_dir ?? data.pagesBuildOutputDir;
    if (pagesOutput !== undefined) {
      if (typeof pagesOutput !== 'string') {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'pages_build_output_dir must be a string.', item.path));
      } else {
        await validatePathExists(projectRoot, item.dir, pagesOutput, item.path, issues, {
          field: 'pages_build_output_dir', expectDirectory: true, missingSeverity: 'info',
        });
      }
    }
    if (data.compatibility_date !== undefined && !isCalendarDate(data.compatibility_date)) {
      issues.push(issue('error', 'CLOUDFLARE_COMPATIBILITY_DATE_INVALID', 'compatibility_date must be a real calendar date in YYYY-MM-DD format.', item.path));
    } else if (!data.compatibility_date) {
      issues.push(issue('error', 'CLOUDFLARE_COMPATIBILITY_DATE_REQUIRED', 'A pinned compatibility_date is required by dotdeployer strict policy.', item.path,
        'Add a compatibility_date (YYYY-MM-DD) to avoid runtime behavior changing between local and hosted deploys.'));
    }
    if (data.compatibility_flags !== undefined && (!Array.isArray(data.compatibility_flags) || data.compatibility_flags.some((flag) => typeof flag !== 'string'))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'compatibility_flags must be an array of strings.', item.path));
    }
    if (data.vars !== undefined && (!data.vars || typeof data.vars !== 'object' || Array.isArray(data.vars))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'vars must be an object.', item.path));
    } else if (data.vars) {
      for (const [key, value] of Object.entries(data.vars)) {
        if (typeof value !== 'string') {
          issues.push(issue('error', 'CLOUDFLARE_VAR_INVALID', `Wrangler vars.${key} must be a string.`, item.path));
        }
        if (/(?:secret|token|password|private[_-]?key|api[_-]?key)/i.test(key)) {
          issues.push(issue('warning', 'POSSIBLE_SECRET_IN_CONFIG', `Wrangler vars key ${key} looks sensitive; vars are part of project configuration and should not hold secrets.`, item.path,
            'Store secret values with wrangler secret or the provider secret manager.'));
        }
      }
    }
    if (data.build !== undefined && (!data.build || typeof data.build !== 'object' || Array.isArray(data.build))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'build must be an object.', item.path));
    } else if (data.build?.command !== undefined && typeof data.build.command !== 'string') {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'build.command must be a string.', item.path));
    }
    if (data.assets !== undefined && (!data.assets || typeof data.assets !== 'object' || Array.isArray(data.assets))) {
      issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'assets must be an object.', item.path));
    } else if (typeof data.assets?.directory === 'string') {
      await validatePathExists(projectRoot, item.dir, data.assets.directory, item.path, issues, {
        field: 'assets.directory', expectDirectory: true, missingSeverity: 'info',
      });
    }
    if (isFreePlan('cloudflare', plan) && data.limits !== undefined) {
      issues.push(issue('warning', 'PLAN_LIMIT_UNVERIFIED', 'Custom Worker limits may require a paid Cloudflare plan; plan eligibility is not checked offline.', item.path));
    }
  }
}

async function validateAppsScript(projectRoot, files, plan, issues) {
  const claspConfigs = files.filter((file) => path.posix.basename(file.path) === '.clasp.json');
  const manifests = files.filter((file) => path.posix.basename(file.path) === 'appsscript.json');
  let claspRootDir = '.';

  for (const clasp of claspConfigs) {
    const data = await parseConfigFile(projectRoot, clasp.path, issues);
    if (data === undefined || !assertObjectConfig(data, clasp.path, issues, 'clasp')) continue;
    if (data.rootDir !== undefined) {
      if (typeof data.rootDir !== 'string' || data.rootDir.trim() === '') {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'clasp rootDir must be a non-empty relative path.', clasp.path));
      } else {
        const resolved = path.posix.normalize(path.posix.join(parentDir(clasp.path) === '.' ? '' : parentDir(clasp.path), data.rootDir));
        if (path.posix.isAbsolute(data.rootDir) || resolved === '..' || resolved.startsWith('../') || path.posix.isAbsolute(resolved)) {
          issues.push(issue('error', 'CONFIG_PATH_ESCAPES_PROJECT', 'clasp rootDir points outside the project directory.', clasp.path));
        } else {
          claspRootDir = resolved || '.';
          await validatePathExists(projectRoot, '.', claspRootDir, clasp.path, issues, {
            field: 'clasp rootDir', expectDirectory: true, missingSeverity: 'error',
          });
        }
      }
    }
  }

  const selectedManifests = manifests.filter((manifest) => {
    if (!claspConfigs.length) return true;
    return manifest.path === (claspRootDir === '.' ? 'appsscript.json' : `${claspRootDir}/appsscript.json`);
  });
  if (!selectedManifests.length) {
    issues.push(issue('error', 'GAS_MANIFEST_MISSING', `No appsscript.json manifest was found${claspRootDir === '.' ? '' : ` under clasp rootDir ${claspRootDir}`}.`, claspConfigs[0]?.path,
      'Add the Apps Script manifest to your clasp rootDir.'));
    return;
  }
  if (selectedManifests.length > 1) issues.push(issue('warning', 'MULTIPLE_PROVIDER_CONFIGS', 'Found multiple Apps Script manifests; each is checked independently.'));
  for (const manifest of selectedManifests) {
    const data = await parseConfigFile(projectRoot, manifest.path, issues);
    if (data === undefined || !assertObjectConfig(data, manifest.path, issues, 'Apps Script manifest')) continue;
    validateString(data.timeZone, manifest.path, 'timeZone', issues, { required: true });
    if (data.runtimeVersion !== undefined && !['V8', 'DEPRECATED_ES5'].includes(data.runtimeVersion)) {
      issues.push(issue('error', 'GAS_RUNTIME_INVALID', 'runtimeVersion must be V8 or DEPRECATED_ES5.', manifest.path));
    } else if (data.runtimeVersion === 'DEPRECATED_ES5') {
      issues.push(issue('warning', 'GAS_RUNTIME_DEPRECATED', 'The Apps Script manifest selects DEPRECATED_ES5.', manifest.path,
        'Use V8 unless this project intentionally depends on the legacy runtime.'));
    } else if (!data.runtimeVersion) {
      issues.push(issue('warning', 'GAS_RUNTIME_UNPINNED', 'runtimeVersion is not set; Apps Script may use a provider default.', manifest.path,
        'Set runtimeVersion to V8 to pin the JavaScript runtime.'));
    }
    if (data.exceptionLogging !== undefined && !['STACKDRIVER', 'CLOUD_LOGGING', 'NONE'].includes(data.exceptionLogging)) {
      issues.push(issue('error', 'GAS_EXCEPTION_LOGGING_INVALID', 'exceptionLogging must be STACKDRIVER, CLOUD_LOGGING, or NONE.', manifest.path));
    }
    if (data.oauthScopes !== undefined && (!Array.isArray(data.oauthScopes) || data.oauthScopes.some((scope) => typeof scope !== 'string' || !scope.startsWith('https://')))) {
      issues.push(issue('error', 'GAS_OAUTH_SCOPES_INVALID', 'oauthScopes must be an array of HTTPS scope strings.', manifest.path));
    }
    if (data.webapp !== undefined) {
      if (!data.webapp || typeof data.webapp !== 'object' || Array.isArray(data.webapp)) {
        issues.push(issue('error', 'CONFIG_FIELD_TYPE', 'webapp must be an object.', manifest.path));
      } else {
        const validAccess = new Set(['MYSELF', 'DOMAIN', 'ANYONE', 'ANYONE_ANONYMOUS']);
        const validExecuteAs = new Set(['USER_ACCESSING', 'USER_DEPLOYING']);
        if (data.webapp.access !== undefined && !validAccess.has(data.webapp.access)) {
          issues.push(issue('error', 'GAS_WEBAPP_ACCESS_INVALID', 'webapp.access must be MYSELF, DOMAIN, ANYONE, or ANYONE_ANONYMOUS.', manifest.path));
        }
        if (data.webapp.executeAs !== undefined && !validExecuteAs.has(data.webapp.executeAs)) {
          issues.push(issue('error', 'GAS_WEBAPP_EXECUTION_INVALID', 'webapp.executeAs must be USER_ACCESSING or USER_DEPLOYING.', manifest.path));
        }
      }
    }
    if (isFreePlan('gas', plan)) {
      issues.push(issue('info', 'PLAN_QUOTAS_NOT_SIMULATED', 'Google Apps Script quotas and account-specific limits cannot be reproduced offline; test OAuth and execution quotas in a test account.', manifest.path));
    }
  }
}

export async function validateProvider(projectRoot, files, provider, plan, issues) {
  switch (provider) {
    case 'render': return validateRender(projectRoot, files, plan, issues);
    case 'railway': return validateRailway(projectRoot, files, plan, issues);
    case 'vercel': return validateVercel(projectRoot, files, plan, issues);
    case 'cloudflare': return validateCloudflare(projectRoot, files, plan, issues);
    case 'gas': return validateAppsScript(projectRoot, files, plan, issues);
    default: return undefined;
  }
}

export async function validateGenericProject(projectRoot, files, issues) {
  const packageFiles = files.filter((file) => file.path === 'package.json');
  let packageJson;
  if (packageFiles.length) {
    try {
      packageJson = JSON.parse(await readFile(packageFiles[0].absolute, 'utf8'));
    } catch (error) {
      issues.push(issue('error', 'PACKAGE_JSON_INVALID', `Invalid package.json: ${error.message}`, 'package.json',
        'Fix package.json syntax before running a provider build.'));
    }
    if (packageJson !== undefined && (!packageJson || typeof packageJson !== 'object' || Array.isArray(packageJson))) {
      issues.push(issue('error', 'PACKAGE_JSON_SHAPE_INVALID', 'package.json must contain a JSON object.', 'package.json'));
      packageJson = undefined;
    }
  }

  if (packageJson) {
    if (packageJson.scripts !== undefined && (!packageJson.scripts || typeof packageJson.scripts !== 'object' || Array.isArray(packageJson.scripts))) {
      issues.push(issue('error', 'PACKAGE_SCRIPTS_INVALID', 'package.json scripts must be an object.', 'package.json'));
    } else if (packageJson.scripts) {
      for (const [name, command] of Object.entries(packageJson.scripts)) {
        if (typeof command !== 'string') issues.push(issue('error', 'PACKAGE_SCRIPT_INVALID', `package.json script ${name} must be a string.`, 'package.json'));
      }
    }
    if (packageJson.type !== undefined && !['module', 'commonjs'].includes(packageJson.type)) {
      issues.push(issue('error', 'PACKAGE_TYPE_INVALID', 'package.json type must be module or commonjs.', 'package.json'));
    }
    if (packageJson.engines?.node !== undefined && typeof packageJson.engines.node !== 'string') {
      issues.push(issue('error', 'PACKAGE_NODE_ENGINE_INVALID', 'package.json engines.node must be a string.', 'package.json'));
    }
    if (packageJson.packageManager !== undefined && typeof packageJson.packageManager !== 'string') {
      issues.push(issue('error', 'PACKAGE_MANAGER_INVALID', 'package.json packageManager must be a string such as npm@10 or pnpm@9.', 'package.json'));
    }
  }

  const locks = [
    ['npm', 'package-lock.json'],
    ['npm', 'npm-shrinkwrap.json'],
    ['pnpm', 'pnpm-lock.yaml'],
    ['yarn', 'yarn.lock'],
    ['bun', 'bun.lock'],
    ['bun', 'bun.lockb'],
  ];
  const presentLocks = locks.filter(([, file]) => files.some((entry) => entry.path === file));
  const declaredManager = packageJson?.packageManager?.split('@')[0]?.toLowerCase();
  if (declaredManager) {
    const managerAliases = new Map([['npm', 'npm'], ['pnpm', 'pnpm'], ['yarn', 'yarn'], ['bun', 'bun']]);
    if (!managerAliases.has(declaredManager)) {
      issues.push(issue('error', 'PACKAGE_MANAGER_UNSUPPORTED', `Unsupported packageManager ${JSON.stringify(packageJson.packageManager)}.`, 'package.json',
        'Use npm, pnpm, yarn, or bun for this local installer.'));
    } else if (!presentLocks.some(([manager]) => manager === declaredManager)) {
      issues.push(issue('error', 'PACKAGE_MANAGER_LOCK_MISSING', `package.json declares ${declaredManager}, but its lockfile is missing.`, 'package.json',
        `Commit the ${declaredManager} lockfile so the local build uses a deterministic dependency graph.`));
    }
  } else if (presentLocks.length > 1 && new Set(presentLocks.map(([manager]) => manager)).size > 1) {
    issues.push(issue('warning', 'MULTIPLE_LOCKFILES', `Multiple package manager lockfiles were found: ${[...new Set(presentLocks.map(([manager]) => manager))].join(', ')}.`, 'package.json',
      'Commit one package manager lockfile or declare packageManager in package.json.'));
  } else if (packageJson && presentLocks.length === 0) {
    issues.push(issue('warning', 'LOCKFILE_MISSING', 'package.json has no recognized lockfile; installs may resolve different dependency versions over time.', 'package.json',
      'Commit a package-manager lockfile for reproducible deploys.'));
  }

  for (const file of files) {
    const basename = path.posix.basename(file.path);
    if (/^\.env(?:\..+)?$/i.test(basename) && !['.env.example', '.env.sample', '.env.template'].includes(basename.toLowerCase())) {
      issues.push(issue('warning', 'ENV_FILE_IN_DEPLOY_CONTEXT', `${file.path} is part of the deployable Git context.`, file.path,
        'Do not commit real credentials in environment files; provide values through the hosting provider secret manager.'));
    }
  }

  const dockerfiles = files.filter((file) => path.posix.basename(file.path).toLowerCase() === 'dockerfile');
  for (const dockerfile of dockerfiles) {
    try {
      const text = await readFile(dockerfile.absolute, 'utf8');
      if (!/^\s*FROM\s+/im.test(text)) {
        issues.push(issue('error', 'DOCKERFILE_FROM_MISSING', 'Dockerfile must contain at least one FROM instruction.', dockerfile.path));
      }
    } catch (error) {
      issues.push(issue('error', 'DOCKERFILE_READ_ERROR', `Cannot read Dockerfile: ${error.message}`, dockerfile.path));
    }
  }
  return { packageJson, presentLocks: presentLocks.map(([, file]) => file), dockerfiles: dockerfiles.map((file) => file.path) };
}

